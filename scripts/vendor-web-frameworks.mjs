#!/usr/bin/env node
// vendor-web-frameworks -- regenerate runtime/data/web-frameworks.json from @vercel/frameworks.
//
//   mkdir /tmp/vf && cd /tmp/vf && echo '{"private":true}' > package.json
//   npm install --no-audit --no-fund @vercel/frameworks@<version>
//   node <repo>/scripts/vendor-web-frameworks.mjs /tmp/vf <repo>/plugins/appfactory-core/runtime/data/web-frameworks.json
//
// WHY VENDOR DATA, NOT CODE. Framework detection is a table plus a ~60-line matcher.
// The table is the part that ages -- new frameworks, renamed packages -- and Vercel
// maintains it for a living (Apache-2.0). The matcher is ported to Python in
// runtime/bin/webdetect.py so a generated project needs no node_modules to ask "what
// is this". This script is the only place that touches the JS; it runs on a dev
// machine, never in a generated project.
//
// WHAT IS LOST IN THE CONVERSION. `getOutputDirName` is a function. It is evaluated
// here against an EMPTY directory, which yields the framework's default. Seven
// frameworks compute it from the tree (angular, docusaurus, docusaurus-2, polymer
// descend into a single subdirectory; hugo, jekyll read a config file). webdetect.py
// does not trust the default: it locates index.html in the built output instead.
import { createRequire } from "node:module";
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const [installDir, outPath] = process.argv.slice(2);
if (!installDir || !outPath) {
  console.error("usage: vendor-web-frameworks.mjs <dir-with-node_modules> <out.json>");
  process.exit(2);
}
const require = createRequire(join(installDir, "package.json"));
const pkgJsonPath = require.resolve("@vercel/frameworks/package.json");
const pkg = JSON.parse(readFileSync(pkgJsonPath, "utf8"));
const { frameworks } = require("@vercel/frameworks");

const setting = (s) => (s && "value" in s ? { value: s.value, ...(s.ignorePackageJsonScript ? { ignorePackageJsonScript: true } : {}) } : null);

const empty = mkdtempSync(join(tmpdir(), "vf-empty-"));
const out = [];
for (const f of frameworks) {
  // Upstream filters experimental entries out unless an env var opts in; so do we, once, here.
  if (f.experimental) continue;
  let defaultOutputDir = null;
  if (f.getOutputDirName) {
    try { defaultOutputDir = await f.getOutputDirName(empty); } catch { defaultOutputDir = null; }
  }
  out.push({
    slug: f.slug,
    name: f.name,
    ...(f.detectors ? { detectors: f.detectors } : {}),
    ...(f.supersedes ? { supersedes: f.supersedes } : {}),
    settings: {
      installCommand: setting(f.settings?.installCommand),
      buildCommand: setting(f.settings?.buildCommand),
      outputDirectory: setting(f.settings?.outputDirectory),
    },
    defaultOutputDir,
    ...(f.useRuntime ? { useRuntime: f.useRuntime.use } : {}),
  });
}
rmSync(empty, { recursive: true });

const doc = {
  source: { package: pkg.name, version: pkg.version, license: pkg.license, repository: "https://github.com/vercel/vercel/tree/main/packages/frameworks" },
  note: "Generated by scripts/vendor-web-frameworks.mjs. Do not edit by hand; regenerate. List order is significant: detection returns the first match.",
  frameworks: out,
};
writeFileSync(outPath, JSON.stringify(doc, null, 1) + "\n");
console.log(`wrote ${out.length} frameworks from ${pkg.name}@${pkg.version} -> ${outPath}`);
